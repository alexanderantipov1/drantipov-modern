// All Q&A flattened for FAQPage JSON-LD (SSR-friendly, crawlable by AI engines)
function buildFaqSchema() {
  const mainEntity = faqs.flatMap((cat) =>
    cat.questions.map((item) => ({
      "@type": "Question",
      name: item.q,
      acceptedAnswer: {
        "@type": "Answer",
        text: item.a,
      },
    })),
  );
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity,
  };
}

