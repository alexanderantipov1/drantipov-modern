export function buildMetadata(article: RevisionArticle): Metadata {
  const canonical = `/ru/for-patients/insights/${article.slug}`
  const enCanonical = `/for-patients/insights/${article.slug}`
  const url = SITE + canonical
  return {
    title: article.metaTitle,
    description: article.metaDescription,
    alternates: {
      canonical,
      languages: { ru: canonical, en: enCanonical, "x-default": enCanonical },
    },
    keywords: article.keywords,
    openGraph: {
      title: article.metaTitle,
      description: article.metaDescription,
      url,
      locale: "ru_RU",
      type: "article",
      images: [{ url: article.image, width: 1200, height: 630, alt: article.heroAlt }],
    },
    twitter: {
      card: "summary_large_image",
      title: article.metaTitle,
      description: article.metaDescription,
      images: [article.image],
    },
  }
}

